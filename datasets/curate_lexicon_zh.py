#!/usr/bin/env python3
"""中文词表人工筛选（对应英文侧 curate_lexicon.py）。

原则与英文侧一致：只保留「错误形式在本地上下文可安全命中」的条目。
依据 MuCGEC dev（1137 句）基线实测（gec-zh/tests/mucgec_eval.rs，
MUCGEC_VERBOSE=1 可复现误报明细）：

移除（错误形式是常见正确字/词，本地命中即误报）：
  (做,作)     95 FP / 0 TP   「做」是极高频正确字
  (即,既)      6 FP / 0 TP   「即」（立即/即使）常见正确
  (既,即)      1 FP / 0 TP
  (其它,其他)  5 FP / 0 TP   「其它」是合法变体
  (按,案)      4 FP / 0 TP   「按」（按照）常见正确
  (报复,抱负)/(抱负,报复)  0/0  双向语境对，本地规则无法区分，归 LLM 路径

新增：
  1. 繁体→简体对（错误形式在正确简正文本中绝不应出现，100% 安全；
     前 12 对来自 MuCGEC dev 实际编辑，其余为常用繁体字）
  2. 错误形式为罕用字的同音对（岐/矢/吾）

用法：`python3 curate_lexicon_zh.py`（在 datasets/ 目录下；幂等）
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
LEX_PATH = os.path.join(HERE, "..", "lexicons", "zh_gec_lexicon.json")

# 移除：错误形式是常见正确字（见文件头注释的实测数据）
REMOVE = {
    ("报复", "抱负"),
    ("抱负", "报复"),
    ("既", "即"),
    ("即", "既"),
    ("做", "作"),
    ("按", "案"),
    ("其它", "其他"),
}

# 繁体→简体：前 12 对来自 MuCGEC dev 实际编辑，其余为常用繁体字
