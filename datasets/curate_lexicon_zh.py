# 同音对：错误形式为罕用字（现代文本中几乎总是错字）
# 注：「矢」曾列入，后因成语「有的放矢」中「矢」为合法用法（1 TP / 1 FP，
# 且成语常见）而移除
SAFE_HOMOPHONES = [
    ("岐", "歧", "「岐」（岐山/岐黄）罕用，现代文本多为「歧」之误"),
    ("吾", "五", "「吾」（文言第一人称）罕用，现代文本多为「五」之误"),
]


def main():
    with open(LEX_PATH, encoding="utf-8") as f:
        lex = json.load(f)

    before = len(lex["confusables"])
    removed = [c for c in lex["confusables"] if (c[0], c[1]) in REMOVE]
    kept = [c for c in lex["confusables"] if (c[0], c[1]) not in REMOVE]

    existing = {(c[0], c[1]) for c in kept}
    added = 0
    for w, r in VARIANTS:
        if (w, r) in existing:
            continue
        kept.append([w, r, "繁体字，简体文本应写作「%s」" % r])
        existing.add((w, r))
        added += 1
    for w, r, note in SAFE_HOMOPHONES:
        if (w, r) in existing:
            continue
        kept.append([w, r, note])
        existing.add((w, r))
        added += 1

    lex["confusables"] = kept

    # 更新 ZH_CONFUSABLE 规则元数据示例（原示例 报复→抱负 已移除）
    for rule in lex["rules"]:
        if rule["id"] == "ZH_CONFUSABLE":
            rule["description"] = "同音/形近错别字与繁简混用"
            rule["examples"] = [
                {"wrong": "他時常迟到", "right": "他时常迟到"},
                {"wrong": "他的态度很岐", "right": "他的态度很歧"},
            ]

    with open(LEX_PATH, "w", encoding="utf-8") as f:
        json.dump(lex, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print(f"confusables: {before} → {len(kept)}（移除 {len(removed)}，新增 {added}）")
    print("移除明细：")
    for c in removed:
        print(f"  - {c[0]}→{c[1]}")
    print("新增示例（末尾 6 条）：")
    for c in kept[-6:]:
        print(f"  + {c[0]}→{c[1]}")


if __name__ == "__main__":
    main()
